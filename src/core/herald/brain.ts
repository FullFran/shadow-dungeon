import { emitBetween, outsidePockets, pocketsBurning, type EmitContext } from './patterns';

/**
 * A Herald of the Eclipse in the fight (data/herald.ts, generated by
 * core/herald/generate.ts). Touhou structure on the shared card framework
 * (core/cards.ts): card `i` holds the i-th equal HP segment and has a
 * timer; emptying the segment or running out the timer moves to the next
 * card (a timeout drops the HP to the segment floor, and the last card's
 * timeout makes the herald fade). Every card change clears the herald's
 * shots. From `phase2.fromCard` on it awakens (a short opening) and plays
 * the phase-2 versions of its cards.
 *
 * Inside a card it repeats a cycle: it moves to its next anchor (static,
 * drifting, blinking or dashing), winds up (the mark is where the target
 * stands as the wind-up begins: aimed layers and lanes use it), attacks
 * (the layers' shots, from core/herald/patterns.ts, the same function the
 * fairness proof simulates), then leaves an opening until its shots are
 * gone. Shots stop at the herald's `maxShots`.
 *
 * Snapshot fields only (co-op): the card in `boss.stance`, the cycle in
 * `boss.comboIndex`, the mark in `ai.aimPoint`, the progress in `ai.modeMs`;
 * every peer regenerates the def from `EnemyState.herald`.
 */

/** The herald of an enemy at the world's tier (null for any other enemy). */
export function heraldOf(state: Pick<WorldState, 'difficulty'>, enemy: Pick<EnemyState, 'herald'>): HeraldDef | null {
  return enemy.herald ? heraldDef(enemy.herald.seed, enemy.herald.depth, worldDifficulty(state)) : null;
}

const cardsOf = (def: HeraldDef, phase: 2 | undefined): readonly HeraldCard[] => (phase === 2 ? def.phase2.cards : def.cards);

/** The card a stance names (phase 1 `herald<i>`, phase 2 `herald<i>x`). */
export function heraldCard(def: HeraldDef, stance: string | null | undefined): HeraldCard | null {
  const m = /^herald(\d+)(x?)$/.exec(stance ?? '');
  if (!m) return null;
  return cardsOf(def, m[2] ? 2 : undefined)[Number(m[1])] ?? null;
}

export const heraldMoveOf = (def: HeraldDef, phase: 2 | undefined): HeraldMove => (phase === 2 ? def.phase2.move : def.move);

/** Where it attacks from on cycle `cycle` of its movement style. */
export function anchorAt(def: HeraldDef, move: HeraldMove, cycle: number): Vec2 {
  const a = def.anchors;
  const i = move === 'static' ? 0 : move === 'drift' ? cycle % 2 : (cycle + (def.seed >>> 3)) % a.length;
  return vec(a[i]!.x, a[i]!.y);
}

/** The emit context of the attack in progress (also the renderer's, for warning lines). */
export const emitContext = (state: Pick<WorldState, 'arena'>, enemy: EnemyState, target?: Vec2): EmitContext => ({
  origin: enemy.pos,
  bossRadius: enemy.radius,
  mark: enemy.ai.aimPoint ?? vec(enemy.pos.x, state.arena.height),
  arena: state.arena,
  ...(target ? { target } : {}),
});

/** The burning pockets of the attack in progress against `pos` (host and guests alike; one contact per attack). */
export function heraldContact(def: HeraldDef, enemy: EnemyState, pos: Vec2): { attack: EnemyAttackDef; touches: boolean } | null {
  if (enemy.ai.mode !== 'attack' || !enemy.boss) return null;
  const card = heraldCard(def, enemy.boss.stance);
  const pockets = card?.layers.find((l): l is Extract<HeraldLayer, { kind: 'pockets' }> => l.kind === 'pockets' && pocketsBurning(l, enemy.ai.modeMs));
  return pockets ? { attack: pockets.attack, touches: outsidePockets(pockets, pos) } : null;
}

const enemyShots = (state: WorldState): number => state.projectiles.reduce((n, p) => n + (p.owner === 'enemy' ? 1 : 0), 0);

function startCard(enemy: EnemyState, def: HeraldDef, index: number, phase: 2 | undefined, events: GameEvent[]): EnemyState {
  const card = cardsOf(def, phase)[index]!;
  events.push({ type: 'bossStance', enemyId: enemy.id, stance: card.id as HeraldStance });
  const { aimPoint: _gone, ...ai } = enemy.ai;
  return { ...enemy, boss: { ...enemy.boss!, stance: card.id as HeraldStance, stanceMs: 0, comboIndex: 0, combosDone: index, ...(phase ? { phase } : {}) }, ai: { ...enterMode(ai, 'approach'), cooldownMs: 700, contact: 'none' } };
}

/** Clears the herald's shots (a card ends: Touhou's bullet cancel). */
const cancelShots = (state: WorldState): WorldState => ({ ...state, projectiles: state.projectiles.filter((p) => p.owner !== 'enemy') });

/** The card in play ended (`hp` or `timeout`): the next card, the awakening, or the fall. */
function nextCard(state: WorldState, enemy: EnemyState, def: HeraldDef, how: 'hp' | 'timeout', events: GameEvent[]): { state: WorldState; enemy: EnemyState } {
  const boss = enemy.boss!;
  const count = def.cards.length;
  const index = boss.combosDone;
  let next = enemy;
  if (how === 'timeout') next = { ...next, hp: Math.min(next.hp, timeoutHp(next.maxHp, index, count)) };
  const cleared = cancelShots(state);
  if (index + 1 >= count) {
    // The last card timed out: the herald fades.
    if (next.hp <= 0) {
      events.push({ type: 'enemyDefeated', enemyId: enemy.id });
      return { state: cleared, enemy: { ...next, hp: 0, alive: false } };
    }
    return { state: cleared, enemy: next };
  }
  if (boss.phase !== 2 && index + 1 >= def.phase2.fromCard) {
    events.push({ type: 'bossStance', enemyId: enemy.id, stance: 'awaken' });
    events.push({ type: 'enemyTelegraph', enemyId: enemy.id, attack: 'awaken', durationMs: def.phase2.transformMs });
    const { aimPoint: _gone, ...ai } = next.ai;
    return {
      state: cleared,
      enemy: { ...next, boss: { ...boss, stance: 'awaken', stanceMs: 0, comboIndex: 0, combosDone: index + 1, phase: 2 }, ai: { ...enterMode(ai, 'transform', def.phase2.transformMs), contact: 'none' } },
    };
  }
  return { state: cleared, enemy: startCard(next, def, index + 1, boss.phase, events) };
}

/** Calls the card's minions to the herald's sides (once per card, while fewer are alive). */
function summon(state: WorldState, enemy: EnemyState, layer: Extract<HeraldLayer, { kind: 'summon' }>): WorldState {
  const alive = state.enemies.filter((e) => e.alive && e.id !== enemy.id).length;
  let next = state;
  layer.species.slice(alive).forEach((species, i) => {
    const side = i % 2 === 0 ? -1 : 1;
    const pos = vec(Math.min(state.arena.width - 30, Math.max(30, enemy.pos.x + side * 60)), Math.min(state.arena.height - 30, enemy.pos.y + 30));
    next = spawnEnemy(next, species, pos);
  });
  return next;
}

/** Fires the shots of the attack in progress with fire times in (fromMs, toMs]. */
function fire(state: WorldState, enemy: EnemyState, def: HeraldDef, card: HeraldCard, fromMs: number, toMs: number, target: Vec2): WorldState {
  let next = state;
  const ctx = emitContext(state, enemy, target);
  for (const layer of card.layers) {
    if (layer.kind === 'summon') {
      if (layer.startMs > fromMs && layer.startMs <= toMs && enemy.boss!.comboIndex === 0) next = summon(next, enemy, layer);
      continue;
    }
    for (const s of emitBetween(layer, fromMs, toMs, ctx)) {
      if (enemyShots(next) >= def.maxShots) return next;
      next = spawnShot(next, enemy, s.shot, s.dir, s.at);
    }
  }
  return next;
}

export function updateHerald(state: WorldState, start: EnemyState, base: HeraldBaseDef, target: Vec2, ms: number, events: GameEvent[]): WorldState {
  const def = heraldOf(state, start);
  if (!def || !start.boss) return state;
  let enemy: EnemyState = { ...start, boss: { ...start.boss, stanceMs: start.boss.stanceMs + ms } };
  const ai = enemy.ai;
  const boss = enemy.boss!;
  const card = heraldCard(def, boss.stance);
  const move = heraldMoveOf(def, boss.phase);

  // The card in play ends by its HP segment or its timer (not while awakening).
  if (card && ai.mode !== 'idle' && ai.mode !== 'transform') {
    const how = cardEnd({ hp: enemy.hp, maxHp: enemy.maxHp, index: boss.combosDone, count: def.cards.length, elapsedMs: boss.stanceMs, timerMs: card.timerMs });
    if (how) {
      const ended = nextCard(state, enemy, def, how, events);
      return replaceEnemy(ended.state, ended.enemy);
    }
  }

  switch (ai.mode) {
    case 'idle':
      if (distance(enemy.pos, target) <= base.aggroRange) enemy = startCard(enemy, def, 0, undefined, events);
      break;
    case 'transform':
      if (modeOver(ai)) enemy = startCard(enemy, def, boss.combosDone, 2, events);
      break;
    case 'approach': {
      if (!card) {
        enemy = startCard(enemy, def, Math.min(boss.combosDone, def.cards.length - 1), boss.phase, events);
        break;
      }
      const anchor = anchorAt(def, move, boss.comboIndex);
      const gap = sub(anchor, enemy.pos);
      const far = distance(anchor, enemy.pos);
      if (far > 2) {
        if (move === 'teleport') {
          events.push({ type: 'heraldBlink', enemyId: enemy.id, from: enemy.pos, to: anchor });
          enemy = { ...enemy, pos: anchor };
        } else {
          const step = Math.min(far, (def.moveSpeed * ms) / 1000);
          enemy = moveEnemy(state, enemy, scale(normalize(gap), step));
        }
      }
      enemy = { ...enemy, facing: towardTarget(target, enemy) };
      // Wind up once rested and standing on the anchor (it always attacks from one: the proof's origins).
      if (ai.cooldownMs <= 0 && distance(anchorAt(def, move, boss.comboIndex), enemy.pos) <= 2) {
        const mark = vec(target.x, target.y);
        const pierce = card.layers.some((l) => l.kind === 'pockets');
        events.push({ type: 'enemyTelegraph', enemyId: enemy.id, attack: card.id, durationMs: card.telegraphMs, ...(pierce ? { pierceRoll: true as const } : {}) });
        enemy = { ...enemy, pos: anchorAt(def, move, boss.comboIndex), ai: { ...enterMode(enemy.ai, 'telegraph', card.telegraphMs), attackDir: towardTarget(mark, enemy), aimPoint: mark, attack: card.id, contact: 'none' } };
      }
      break;
    }
    case 'telegraph':
      if (!card) break;
      if (modeOver(ai)) {
        events.push({ type: 'enemyAttack', enemyId: enemy.id, attack: card.id });
        enemy = { ...enemy, ai: { ...enterMode(ai, 'attack', card.attackMs), contact: 'none' } };
        // Parts at 0 fire as the attack starts.
        state = fire(state, enemy, def, card, -1, 0, target);
      }
      break;
    case 'attack': {
      if (!card) break;
      state = fire(state, enemy, def, card, ai.modeMs - ms, Math.min(ai.modeMs, card.attackMs), target);
      const zone = heraldContact(def, enemy, state.player.pos);
      if (zone) {
        const hit = contactPlayer(state, enemy, zone.attack, zone.touches, events);
        state = hit.state;
        enemy = { ...enemy, ai: { ...enemy.ai, contact: hit.contact } };
      }
      if (modeOver(ai)) enemy = { ...enemy, ai: { ...enterMode(enemy.ai, 'recover', card.recoverMs), contact: 'none' } };
      break;
    }
    case 'recover':
      if (card && modeOver(ai)) enemy = { ...enemy, boss: { ...enemy.boss!, comboIndex: boss.comboIndex + 1 }, ai: { ...enterMode(ai, 'approach'), cooldownMs: card.restMs } };
      break;
    default:
      break;
  }
  return replaceEnemy(state, enemy);
}
