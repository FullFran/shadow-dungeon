import { floorLabel, median, runCleared, type BandCheck } from './bands';
import type { FloorResult, RunResult } from './runner';
import type { ArenaResult, SweepResults } from './sweep';

/**
 * The balance report (`npm run balance` → reports/balance/latest.md and
 * latest.json). The markdown carries no date or timing, so two reports differ
 * only where the balance did: diff it before and after a rebalance.
 */

const pct = (x: number): string => (Number.isFinite(x) ? `${Math.round(x * 100)}%` : '–');
const sec = (ms: number): string => (Number.isFinite(ms) ? `${(ms / 1000).toFixed(0)} s` : '–');
const ms = (x: number): string => (Number.isFinite(x) ? `${x.toFixed(0)}` : '–');
const minOf = (xs: readonly number[]): number => (xs.length ? Math.min(...xs) : Number.NaN);
const maxOf = (xs: readonly number[]): number => (xs.length ? Math.max(...xs) : Number.NaN);

function table(head: readonly string[], rows: readonly (readonly string[])[]): string {
  return [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
}

function runRow(runs: readonly RunResult[]): string[] {
  const { tier, bot, party } = runs[0]!.scenario;
  const floors = runs.flatMap((r) => r.floors);
  const pierce = floors.reduce((n, f) => n + f.hitsPierce, 0);
  const hits = floors.reduce((n, f) => n + f.hits, 0);
  const died = runs.filter((r) => r.outcome === 'defeat');
  const deathAt = [...new Set(died.map((r) => floorLabel(r.floors[r.floors.length - 1]!)))].join(', ');
  return [
    tier,
    bot,
    String(party),
    `${runs.filter(runCleared).length}/${runs.length}`,
    String(median(runs.map((r) => r.floors.length))),
    died.length ? `${died.length} (${deathAt})` : '0',
    runs.some((r) => r.outcome === 'timeout') ? String(runs.filter((r) => r.outcome === 'timeout').length) : '0',
    pct(median(floors.map((f) => f.damage / f.maxHp))),
    pct(maxOf(floors.map((f) => f.maxHitShare))),
    hits ? `${pierce}/${hits}` : '0',
    sec(median(floors.flatMap((f) => f.enemyTtkMs))),
  ];
}

function arenaRow(arenas: readonly ArenaResult[]): string[] {
  const { tier, bot, party } = arenas[0]!.scenario;
  const rs = arenas.map((a) => a.result);
  const ttk = rs.map((r) => r.bossTtkMs).filter((t): t is number => t !== null);
  return [
    floorLabel(rs[0]!),
    tier,
    bot,
    String(party),
    `${ttk.length}/${rs.length}`,
    sec(median(ttk)),
    String(rs.filter((r) => r.outcome === 'died').length),
    pct(median(rs.map((r) => r.damage / r.maxHp))),
    pct(maxOf(rs.map((r) => r.maxHitShare))),
    `${rs.reduce((n, r) => n + r.hitsPierce, 0)}/${rs.reduce((n, r) => n + r.hits, 0)}`,
  ];
}

function fairnessRow(tier: string, floors: readonly FloorResult[]): string[] {
  const tel = floors.flatMap((f) => f.telegraphMs);
  const choice = floors.flatMap((f) => f.choiceTelegraphMs);
  return [
    tier,
    ms(minOf(tel)),
    ms(median(tel)),
    ms(minOf(choice)),
    ms(median(choice)),
    String(maxOf(floors.map((f) => f.maxSimultaneousTelegraphs))),
    String(floors.reduce((n, f) => n + f.unseenAttacks, 0)),
    String(maxOf(floors.map((f) => f.maxSimultaneousUnseen))),
    String(floors.reduce((n, f) => n + f.blindHits, 0)),
    String(floors.reduce((n, f) => n + f.untelegraphedAttacks, 0)),
  ];
}

function by<T>(items: readonly T[], key: (t: T) => string): T[][] {
  const map = new Map<string, T[]>();
  for (const item of items) {
    const k = key(item);
    map.set(k, [...(map.get(k) ?? []), item]);
  }
  return [...map.values()];
}

export function renderMarkdown(sweep: SweepResults, checks: readonly BandCheck[]): string {
  const c = sweep.config;
  const fails = checks.filter((x) => x.status === 'fail');
  const known = checks.filter((x) => x.status === 'warn' && x.known);
  const warns = checks.filter((x) => x.status === 'warn' && !x.known);
  const out: string[] = [];
  out.push('# Balance report');
  out.push('');
  out.push('Generated by `npm run balance` (src/sim, docs/gdd.md §9 "Arnés de balance"). Bots play headless with fixed seeds; the report is deterministic, so diff it before and after a rebalance.');
  out.push('');
  out.push(`Sweep: dungeons ${c.dungeons.length}, tiers ${c.tiers.join('/')}, bots ${c.bots.join('/')}, party ${c.parties.join('/')}, seeds ${c.seeds.join(',')}, Sima floors ≤ ${c.maxFloors}; arenas in isolation for ${c.arenaBots.join('/')} (fresh level-1 starter). ${sweep.runs.length} runs, ${sweep.arenas.length} arena fights.`);
  out.push('');
  out.push(`**Gate: ${fails.length ? `FAIL (${fails.length})` : 'PASS'}** · ${known.length} known fairness violations · ${warns.length} performance warnings · ${checks.filter((x) => x.status === 'pass').length} passes.`);
  out.push('');
  if (fails.length) {
    out.push('## Failures (fairness, not known)');
    out.push('');
    out.push(table(['band', 'scope', 'measured', 'target'], fails.map((x) => [x.band, x.scope, x.value, x.target])));
    out.push('');
  }
  out.push('## Known fairness violations (current content)');
  out.push('');
  out.push(known.length ? table(['band', 'scope', 'measured', 'target', 'why'], known.map((x) => [x.band, x.scope, x.value, x.target, x.known ?? ''])) : 'None.');
  out.push('');
  out.push('## Performance warnings');
  out.push('');
  out.push(warns.length ? table(['band', 'scope', 'measured', 'target'], warns.map((x) => [x.band, x.scope, x.value, x.target])) : 'None.');
  out.push('');
  for (const dungeon of c.dungeons) {
    out.push(`## ${dungeon}`);
    out.push('');
    out.push('### Runs (floor by floor)');
    out.push('');
    const runs = sweep.runs.filter((r) => r.scenario.dungeon === dungeon);
    out.push(
      table(
        ['tier', 'bot', 'party', 'cleared', 'floors (median)', 'deaths (where)', 'timeouts', 'HP lost / floor (median)', 'max hit', 'positional hits', 'enemy TTK (median)'],
        by(runs, (r) => `${r.scenario.tier}/${r.scenario.bot}/${r.scenario.party}`).map(runRow),
      ),
    );
    out.push('');
    const arenas = sweep.arenas.filter((a) => a.scenario.dungeon === dungeon);
    if (arenas.length) {
      out.push('### Arenas in isolation');
      out.push('');
      out.push(
        table(
          ['arena', 'tier', 'bot', 'party', 'felled', 'boss TTK (median)', 'deaths', 'HP lost (median)', 'max hit', 'positional hits'],
          by(arenas, (a) => `${a.result.floor}/${a.scenario.tier}/${a.scenario.bot}/${a.scenario.party}`).map(arenaRow),
        ),
      );
      out.push('');
    }
    out.push('### Telegraphs and threats (every bot and party)');
    out.push('');
    const floorsOf = (tier: string) => [...runs.filter((r) => r.scenario.tier === tier).flatMap((r) => r.floors), ...arenas.filter((a) => a.scenario.tier === tier).map((a) => a.result)];
    out.push(
      table(
        ['tier', 'telegraph min ms', 'median', 'positional min ms', 'median', 'max at once', 'off-screen starts', 'max off-screen at once', 'blind hits', 'untelegraphed attacks'],
        c.tiers.map((t) => fairnessRow(t, floorsOf(t))),
      ),
    );
    out.push('');
  }
  return out.join('\n');
}

/** Everything, for scripts: config, band checks and every floor result. */
export const renderJson = (sweep: SweepResults, checks: readonly BandCheck[]): string => JSON.stringify({ config: sweep.config, checks, runs: sweep.runs, arenas: sweep.arenas });

