export const COMBAT_ICON_IDS: string[] = Object.keys(COMBAT_ICONS);

export type { PixelRect };

/** The icon's horizontal runs of one colour (what is painted), for the canvas and the tests. */
export const iconRuns = (i: PixelIcon): PixelRect[] => pixelIconRects(i);

/** Draws `icon` with its top-left at (x, y), `px` HUD pixels per icon pixel (whole numbers keep it crisp). `alpha` dims it. */
export function drawIcon(ctx: CanvasRenderingContext2D, i: PixelIcon, x: number, y: number, px = 1, alpha = 1): void {
  const before = ctx.globalAlpha;
  ctx.globalAlpha = before * alpha;
  for (const r of iconRuns(i)) {
    ctx.fillStyle = r.fill;
    ctx.fillRect(x + r.x * px, y + r.y * px, r.w * px, px);
  }
  ctx.globalAlpha = before;
}
