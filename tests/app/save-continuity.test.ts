import { describe, expect, it } from 'vitest';
import { memoryStore, type KeyValueStore } from '../../src/adapters/storage';
import { httpAccountApi } from '../../src/adapters/account-api';
import { createAccount } from '../../src/app/account';
import { observeKey, readRemote, type Timers } from '../../src/app/cloud-sync';
import { loadSave, parseSave, SAVE_KEY, SAVE_VERSION, writeSave, type SaveData } from '../../src/app/save';
import { defaultSettings, loadSettings } from '../../src/app/settings';
import { rosterOf } from '../../src/core/collection';
import { familyProgress } from '../../src/core/achievements';
import { recordPast } from '../../src/app/progress';
import { readRecords, RECORDS_KEY } from '../../src/town/records';
import { LEADERBOARD_KEY, readBoard } from '../../src/town/leaderboard';
import { readShrine, SHRINE_KEY } from '../../src/town/shrine-records';
import v2Storage from './fixtures/storage-v2-b90c45a.json';
import v3Storage from './fixtures/storage-v3-245f309.json';

/**
 * Progress continuity (odd/tasks/progress-continuity.md): the localStorage a
 * player had on the builds deployed before the v3 and v4 saves, generated by
 * running those builds' own writers (b90c45a: save v2; 245f309: save v3), must
 * read through today's code with every value intact.
 */
const FIXTURES = { 'v2 (b90c45a)': v2Storage, 'v3 (245f309)': v3Storage } as const;

const deviceWith = (contents: Record<string, string>): KeyValueStore => {
  const store = memoryStore();
  for (const [key, value] of Object.entries(contents)) store.set(key, value);
  return store;
};

/** Everything the old build stored in the save, minus its version. */
const oldSave = (contents: Record<string, string>): Record<string, unknown> => {
  const { version: _version, ...rest } = JSON.parse(contents[SAVE_KEY]!) as Record<string, unknown>;
  return rest;
};

const noTimers: Timers = { set: () => null, clear: () => {} };

describe('progress continuity from the deployed saves', () => {
  for (const [name, contents] of Object.entries(FIXTURES)) {
    describe(name, () => {
      it('keeps coins, upgrades, learned moves, Mejoras and the collection exactly', () => {
        const save = loadSave(deviceWith(contents));
        const old = oldSave(contents);
        expect(save.version).toBe(SAVE_VERSION);
        // Every field the old build wrote reads back identical (nothing filtered, reordered or clamped).
        for (const [field, value] of Object.entries(old)) expect(save[field as keyof SaveData], field).toEqual(value);
        // Ranks and learned moves of all four starters survive.
        for (const starter of ['mimikyu', 'zorua', 'litwick', 'cubone'] as const) {
          expect(save.learned?.[starter]?.length, starter).toBe(3);
          expect(Object.keys(save.ranks?.[starter] ?? {}).length, starter).toBe(3);
        }
      });

      it('keeps the selected species, its custom loadout and the other settings', () => {
        const store = deviceWith(contents);
        const stored = JSON.parse(contents['mazmorra-sombria.settings']!) as Record<string, unknown>;
        const settings = loadSettings(store, defaultSettings('en'), rosterOf(loadSave(store)));
        for (const field of ['species', 'starterChosen', 'loadout', 'difficulty', 'nickname', 'masterVolume', 'language'] as const) expect(settings[field], field).toEqual(stored[field]);
      });

      it('keeps the notice board records, the Sima leaderboard and the shrine records', () => {
        const store = deviceWith(contents);
        expect(readRecords(store)).toEqual(JSON.parse(contents[RECORDS_KEY]!));
        expect(readBoard(store)).toEqual(expect.arrayContaining(JSON.parse(contents[LEADERBOARD_KEY]!)));
        expect(readBoard(store)).toHaveLength(JSON.parse(contents[LEADERBOARD_KEY]!).length);
        expect(readShrine(store)).toEqual(JSON.parse(contents[SHRINE_KEY]!));
      });

      it('as a guest: no network request at start or on a save write, and the save is kept', async () => {
        const store = deviceWith(contents);
        const calls: string[] = [];
        const api = httpAccountApi('https://example.invalid', async (input) => {
          calls.push(String(input));
          throw new Error('no network in this test');
        });
        const account = createAccount({ api, store, timers: noTimers, onNotice: () => {}, onChange: () => {} });
        const game = observeKey(store, SAVE_KEY, () => account.saveChanged());
        await account.start();
        account.online();
        account.flush();
        expect(account.state()).toEqual({ kind: 'guest' });
        const before = loadSave(game);
        writeSave(game, { ...before, coins: before.coins + 10 });
        expect(calls).toEqual([]);
        expect(loadSave(game)).toEqual({ ...before, coins: before.coins + 10 });
        expect(loadSave(game).owned).toEqual(oldSave(contents).owned);
      });
    });
  }

  it('reads an early v3 save (flat material counts) as Normal materials', () => {
    const save = parseSave(JSON.stringify({ version: 3, coins: 500, upgrades: { vitality: 1 }, owned: ['abra'], materials: { abra: 4 }, pity: 3 }));
    expect(save).toMatchObject({ coins: 500, upgrades: { vitality: 1 }, owned: ['abra'], materials: { abra: { normal: 4 } }, pity: 3 });
  });

  it('round-trips a save written by today’s code with every v4 field', () => {
    const today: SaveData = {
      version: SAVE_VERSION,
      coins: 987,
      upgrades: { vitality: 5, insight: 2 },
      learned: { zoroark: ['shadow-claw'], chandelure: ['night-shade'] },
      ranks: { zoroark: { 'fury-swipes': 2 }, alakazam: { psychic: 1 } },
      owned: ['zoroark', 'chandelure', 'alakazam', 'empoleon'],
      awakened: { mimikyu: 1 },
      materials: { abra: { normal: 1, hard: 2 }, zorua: { nightmare: 1 } },
      pity: 4,
      achievements: { 'gacha-first-pull': '2026-10-26' },
      earned: 5432,
      missions: { accepted: [], claimed: [] },
      shinies: ['zorua', 'abra'],
      shinyWorn: ['abra'],
      shinyPity: 12,
    };
    const store = memoryStore();
    writeSave(store, today);
    const { missions: _empty, ...rest } = today;
    expect(loadSave(store)).toEqual(rest);
  });

  it('achievements unlocked on load survive a reload and the trip through the cloud', () => {
    const store = deviceWith(v2Storage);
    const { save } = recordPast(store, Date.UTC(2026, 9, 26));
    expect(Object.keys(save.achievements ?? {}).length).toBeGreaterThan(0);
    // A reload is a fresh read of the same strings (the achievements window reads loadSave(store).achievements).
    const reloaded = loadSave(deviceWith({ [SAVE_KEY]: store.get(SAVE_KEY)! }));
    expect(reloaded).toEqual(save);
    expect(familyProgress(reloaded.achievements ?? {}).reduce((n, f) => n + f.done, 0)).toBe(Object.keys(save.achievements ?? {}).length);
    // Cloud sync pushes the sanitized save and reads it back the same way.
    expect(readRemote(JSON.parse(JSON.stringify(reloaded)))).toEqual(save);
  });
});
