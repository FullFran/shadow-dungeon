/**
 * `npx vite-node tools/move-progression-ttk.ts`: how much faster a fully
 * invested build kills the bosses (odd/tasks/move-progression.md T4). For
 * each starter, every fixed arena (guardians, mid-bosses, the Sima's echoes
 * to floor 5) is played in isolation by the perfect and average bots (four
 * slots), on Normal and Nightmare, two seeds, with (a) the default loadout
 * unranked, (b) the default loadout at rank +2 and (c) the full-investment
 * build (data/tutor.ts `FULL_BUILD`) at rank +2. Writes
 * reports/balance/move-progression-ttk.md.
 *
 *   npx vite-node tools/move-progression-ttk.ts [--out=dir] [--try=zorua:feint-attack,night-daze,nasty-plot,dark-pulse]
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DUNGEONS } from '../src/data/dungeons';
import type { Difficulty } from '../src/data/difficulty';
import type { StarterId } from '../src/data/learnsets';
import type { MoveId } from '../src/data/moves';
import { SPECIES } from '../src/data/species';
import { FULL_BUILD, MAX_RANK } from '../src/data/tutor';
import type { BotKind } from '../src/sim/bots';
import { arenaFloors, runFloor, type FloorResult, type RunOptions } from '../src/sim/runner';

const args = process.argv.slice(2);
const outDir = args.find((a) => a.startsWith('--out='))?.split('=')[1] ?? join('reports', 'balance');
// `--try=<starter>:<m1>,<m2>,<m3>,<m4>`: only that starter, with that build instead of FULL_BUILD (exploration).
const tried = args.find((a) => a.startsWith('--try='))?.split('=')[1]?.split(':');
const STARTERS: readonly StarterId[] = tried ? [tried[0] as StarterId] : ['mimikyu', 'zorua', 'litwick', 'cubone'];
const buildOf = (s: StarterId): readonly MoveId[] => (tried ? (tried[1]!.split(',') as MoveId[]) : FULL_BUILD[s]);
const TIERS: readonly Difficulty[] = ['normal', 'nightmare'];
const BOTS: readonly BotKind[] = ['perfect', 'average'];
const SEEDS = [1, 2];
const MAX_FLOORS = 5;

type Fight = { key: string; boss: string; result: FloorResult };

function fights(options: RunOptions): Fight[] {
  const out: Fight[] = [];
  for (const d of DUNGEONS)
    for (const tier of TIERS)
      for (const bot of BOTS)
        for (const seed of SEEDS)
          for (const floor of arenaFloors(d.id, MAX_FLOORS)) {
            const result = runFloor({ dungeon: d.id, tier, bot, party: 1, seed }, floor, { maxFloors: MAX_FLOORS, slots: true, ...options });
            out.push({ key: `${d.id}/${floor}/${tier}/${bot}/${seed}`, boss: result.boss ?? '?', result });
          }
  return out;
}

const median = (xs: readonly number[]): number => {
  if (xs.length === 0) return Number.NaN;
  const s = [...xs].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? s[m]! : (s[m - 1]! + s[m]!) / 2;
};
const pct = (x: number) => `${Math.round(x * 100)} %`;
const secs = (ms: number) => `${(ms / 1000).toFixed(1)} s`;
const ranked = (moves: readonly (MoveId | null)[]) => Object.fromEntries(moves.filter((m): m is MoveId => m !== null).map((m) => [m, MAX_RANK])) as Partial<Record<MoveId, number>>;
const won = (fs: Fight[]) => fs.filter((f) => f.result.bossTtkMs !== null);
const dmg = (fs: Fight[]) => Math.round(fs.reduce((s, f) => s + f.result.damage, 0) / Math.max(1, fs.length));

/** Paired speed-ups of `other` over `base`: fights both won. */
function speedups(base: Fight[], other: Fight[]): { boss: string; up: number }[] {
  return base.flatMap((b) => {
    const o = other.find((f) => f.key === b.key);
    return b.result.bossTtkMs !== null && o?.result.bossTtkMs ? [{ boss: b.boss, up: 1 - o.result.bossTtkMs / b.result.bossTtkMs }] : [];
  });
}

const lines: string[] = [
  '# Move progression: boss TTK, default vs full investment',
  '',
  "Generated by `npx vite-node tools/move-progression-ttk.ts` (odd/tasks/move-progression.md T4). Every fixed arena (guardians, mid-bosses, the Sima's echoes to floor 5) in isolation, perfect and average bots with the four slots, Normal and Nightmare, seeds 1–2, solo (72 fights per build). Default = the starter's default loadout without Mejoras; Default ++ = the same moves at rank +2; Full ++ = its full-investment build (`FULL_BUILD`, Maestro moves where they pay) at rank +2. Speed-up = 1 − (TTK / default TTK), median over the fights both builds won (paired). The bots play the fast slot most and use boost and area on a schedule: they do not exploit zones, marks, i-frames or super-armor on purpose, so this is a floor for what a player gets.",
  '',
  '| Starter | Full build | Won (default / default ++ / full ++) | Median boss TTK (default / default ++ / full ++) | Speed-up default ++ | Speed-up full ++ | Damage taken per fight (default / full ++) |',
  '|---|---|---|---|---|---|---|',
];
const perBoss: string[] = ['', '## Per boss (median paired speed-up of full ++)', '', '| Starter | Boss | Pairs | Speed-up |', '|---|---|---|---|'];
const started = performance.now();
for (const starter of STARTERS) {
  const kit = SPECIES[starter].defaultLoadout;
  const build = buildOf(starter);
  const base = fights({ species: starter, loadout: kit });
  const kitUp = fights({ species: starter, loadout: kit, moveRanks: ranked(kit) });
  const full = fights({ species: starter, loadout: build, moveRanks: ranked(build) });
  const upKit = speedups(base, kitUp);
  const upFull = speedups(base, full);
  const ttk = (fs: Fight[]) => secs(median(won(fs).map((f) => f.result.bossTtkMs!)));
  lines.push(
    `| ${starter} | ${build.join(' · ')} | ${won(base).length} / ${won(kitUp).length} / ${won(full).length} | ${ttk(base)} / ${ttk(kitUp)} / ${ttk(full)} | ${pct(median(upKit.map((p) => p.up)))} | ${pct(median(upFull.map((p) => p.up)))} | ${dmg(base)} / ${dmg(full)} |`,
  );
  for (const boss of [...new Set(upFull.map((p) => p.boss))].sort()) {
    const mine = upFull.filter((p) => p.boss === boss).map((p) => p.up);
    perBoss.push(`| ${starter} | ${boss} | ${mine.length} | ${pct(median(mine))} |`);
  }
  console.log(`${starter}: won ${won(base).length}/${won(kitUp).length}/${won(full).length}; speed-up default++ ${pct(median(upKit.map((p) => p.up)))}, full++ ${pct(median(upFull.map((p) => p.up)))} (${build.join(',')})`);
}
lines.push(...perBoss);
if (!tried) {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'move-progression-ttk.md'), `${lines.join('\n')}\n`);
}
console.log(`ttk: ${((performance.now() - started) / 1000).toFixed(1)} s${tried ? '' : ` → ${join(outDir, 'move-progression-ttk.md')}`}`);
