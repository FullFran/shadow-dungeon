/**
 * `npx vite-node tools/degenerate-builds.ts`: the degenerate-build audit
 * (odd/tasks/degenerate-builds.md B2). The tank bot (src/sim/tank.ts) never
 * dodges and face-tanks every card of every card boss on Nightmare, each
 * card held forever (it can only end with the player's death), for each
 * audited build (starter × loadout at rank +2) bare and with a defensive
 * item set. A card still standing after 180 s is one the build out-heals
 * (immortal). Also: i-frame and super-armor uptime, HP healed per second.
 * Writes reports/balance/degenerate-builds-audit.md.
 *
 *   npx vite-node tools/degenerate-builds.ts [--out=dir] [--only=<build id>,...] [--items=a,b,c]
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { ItemId } from '../src/data/items';
import { AUDIT_BUILDS, auditBuild, TANK_ITEMS } from '../src/sim/tank';

const args = process.argv.slice(2);
const flag = (name: string) => args.find((a) => a.startsWith(`--${name}=`))?.split('=')[1];
const outDir = flag('out') ?? join('reports', 'balance');
const only = flag('only');
const custom = flag('items');
const sets: readonly { name: string; items: readonly ItemId[] }[] = custom
  ? [{ name: custom, items: custom.split(',') as ItemId[] }]
  : [
      { name: 'none', items: [] },
      { name: 'tank items', items: TANK_ITEMS },
    ];

const pct = (x: number) => `${Math.round(x * 100)} %`;
const lines = [
  '# Degenerate-build audit (tank bot)',
  '',
  'Generated by `npx vite-node tools/degenerate-builds.ts` (odd/tasks/degenerate-builds.md B2). The tank bot never rolls: it walks into the boss and uses its best ready slot. Every card of the eight card bosses on Nightmare (46 cards) is held forever (its clock and the boss HP are put back every step), so a fight only ends when the player faints. Immortal = still standing after 180 s. Flipped = immortal on a card that kills the same starter\'s bare, unranked default kit within 60 s (a lethal card the build turned harmless; the other immortal cards are ones a face-tanker already holds for minutes). Uptimes and healing are over all the fight time. Builds are at rank +2 on every move, at the floor\'s expected level. Tank items: ' +
    TANK_ITEMS.join(', ') +
    '.',
  '',
  '| Build | Moves | Items | Immortal cards | Flipped fast cards | Median time to faint | i-frame uptime | Super-armor uptime | Healed per second (% max HP) |',
  '|---|---|---|---|---|---|---|---|---|',
];
const started = performance.now();
for (const build of AUDIT_BUILDS) {
  if (only && !only.split(',').includes(build.id)) continue;
  for (const set of sets) {
    const a = auditBuild(build, set.items);
    const row = `| ${build.id} | ${build.loadout.join(' · ')} | ${set.name} | ${a.immortal} / ${a.cards} | ${a.flipped} | ${(a.medianMs / 1000).toFixed(0)} s | ${pct(a.iframeShare)} | ${pct(a.wardShare)} | ${(a.healPerSecond * 100).toFixed(2)} % |`;
    lines.push(row);
    console.log(row);
  }
}
if (!only && !custom) {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'degenerate-builds-audit.md'), `${lines.join('\n')}\n`);
}
console.log(`audit: ${((performance.now() - started) / 1000).toFixed(1)} s`);
